def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description=__doc__,
        epilog=(
            "With no command, the updater synchronizes SKAdNetwork IDs, "
            "resources, and generated manifests. Compatibility aliases "
            "--generate, --check, --refresh, --sync-skadnetwork, and "
            "--sync-resources are also accepted."
        ),
    )
    commands = parser.add_subparsers(dest="command", required=True)

    update_parser = commands.add_parser(
        "update",
        help=(
            "run the normal iOS update: SKAdNetwork IDs, resources, "
            "and generated manifests"
        ),
    )
    add_output_arguments(update_parser)
    add_archive_argument(update_parser)
    add_timeout_argument(update_parser)
    add_workers_argument(update_parser)

    generate_parser = commands.add_parser(
        "generate", help="generate deterministic iOS manifests"
    )
    add_output_arguments(generate_parser)

    check_parser = commands.add_parser(
        "check",
        help="check generated manifests and checked-in resources",
    )
    add_output_arguments(check_parser)

    refresh_parser = commands.add_parser(
        "refresh",
        help="validate the exact pin against live CocoaPods metadata",
    )
    add_timeout_argument(refresh_parser)
    add_workers_argument(refresh_parser)

    skadnetwork_parser = commands.add_parser(
        "sync-skadnetwork",
        help=(
            "update the pinned identifiers from AppLovin and regenerate "
            "iOS manifests"
        ),
    )
    add_output_arguments(skadnetwork_parser)
    add_timeout_argument(skadnetwork_parser)
    add_workers_argument(skadnetwork_parser)

    resources_parser = commands.add_parser(
        "sync-resources",
        help=(
            "verify the official archive and atomically refresh the "
            "checked-in resource bundle"
        ),
    )
    add_archive_argument(resources_parser)
    add_resource_bundle_argument(resources_parser)
    add_timeout_argument(resources_parser)
    return parser


def main(argv: Sequence[str] | None = None) -> int:
    raw_values = list(sys.argv[1:] if argv is None else argv)
    values = normalize_aliases(
        raw_values,
        (
            "update",
            "generate",
            "check",
            "refresh",
            "sync-skadnetwork",
            "sync-resources",
        ),
    )
    if not values:
        values = ["update"]
    args = build_parser().parse_args(values)
    try:
        if args.command == "update":
            return update(args)
        if args.command == "generate":
            return generate_or_check(args, False)
        if args.command == "check":
            return generate_or_check(args, True)
        if args.command == "refresh":
            return refresh(args)
        if args.command == "sync-skadnetwork":
            return sync_skadnetwork(args)
        return sync_resources(args)
    except UpdaterError as error:
        print(f"error: {error}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    raise SystemExit(main())
